const c = (cx, cy, r) => `<circle cx="${cx}" cy="${cy}" r="${r}"/>`;
const e = (cx, cy, rx, ry) => `<ellipse cx="${cx}" cy="${cy}" rx="${rx}" ry="${ry}"/>`;
const r = (x, y, w, h, rx = 0) => `<rect x="${x}" y="${y}" width="${w}" height="${h}" rx="${rx}"/>`;
const p = d => `<path d="${d}"/>`;
const poly = pts => `<polygon points="${pts}"/>`;
const eye = (x, y, s = 9) => `<circle cx="${x}" cy="${y}" r="${s}" fill="#1f2937"/><circle cx="${x + s * .35}" cy="${y - s * .35}" r="${s * .35}" fill="#fff"/>`;
const star5 = (x, y, R, rr = R * .45) => poly(Array.from({ length: 10 }, (_, i) => {
  const a = -Math.PI / 2 + i * Math.PI / 5, d = i % 2 ? rr : R;
  return `${(x + d * Math.cos(a)).toFixed(1)},${(y + d * Math.sin(a)).toFixed(1)}`;
}).join(' '));

